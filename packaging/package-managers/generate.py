#!/usr/bin/env python3
"""Generate the tap and bucket from a published stable GitHub Release."""

import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import quote


REPOSITORY = "https://github.com/dccif/KeySteer"

# Snapshot files rather than hard-linking them: KeySteer saves configuration
# atomically, which replaces the file and would break Scoop's persistent link.
BACKUP = [
    "$appRoot = (Split-Path -Parent $dir) + [IO.Path]::DirectorySeparatorChar",
    "$running = Get-Process KeySteer -ErrorAction SilentlyContinue | Where-Object { $_.Path -and $_.Path.StartsWith($appRoot, [StringComparison]::OrdinalIgnoreCase) }",
    "if ($running) { throw 'Exit KeySteer before updating or uninstalling it.' }",
    "$data = Join-Path $persist_dir 'data'",
    "New-Item -ItemType Directory -Path $data -Force | Out-Null",
    "Get-ChildItem -LiteralPath $data -File | Where-Object { $_.Name -like 'keysteer.*.toml' -or $_.Name -eq 'workspace.ksw' } | ForEach-Object { Remove-Item -LiteralPath $_.FullName -Force -ErrorAction Stop }",
    "Get-ChildItem -LiteralPath $dir -File | Where-Object { ($_.Name -like 'keysteer.*.toml' -and $_.Name -ne 'keysteer.default.toml') -or $_.Name -eq 'workspace.ksw' } | ForEach-Object { Copy-Item -LiteralPath $_.FullName -Destination $data -Force -ErrorAction Stop }",
]
RESTORE = [
    "$data = Join-Path $persist_dir 'data'",
    "if (Test-Path -LiteralPath $data) {",
    "    Get-ChildItem -LiteralPath $data -File | Where-Object { ($_.Name -like 'keysteer.*.toml' -and $_.Name -ne 'keysteer.default.toml') -or $_.Name -eq 'workspace.ksw' } | ForEach-Object { Copy-Item -LiteralPath $_.FullName -Destination $dir -Force -ErrorAction Stop }",
    "}",
]


def generate(release, root, assets_dir=None):
    if release.get("draft") or release.get("prerelease"):
        raise ValueError("Only published stable releases may update package managers")
    tag = release["tag_name"]
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+-]*", tag):
        raise ValueError("Unsupported release tag")
    assets = {asset["name"]: asset for asset in release["assets"]}
    # The archive version is authoritative even if a custom release tag is used.
    versions = {
        match[1]
        for name in assets
        if (match := re.fullmatch(r"KeySteer-v(\d+\.\d+\.\d+)-aarch64-pc-windows-msvc\.zip", name))
    }
    if len(versions) != 1:
        raise ValueError("Release must contain one stable Windows ARM64 package")
    version = versions.pop()
    base = f"{REPOSITORY}/releases/download/{quote(tag, safe='')}"

    def package(target):
        name = f"KeySteer-v{version}-{target}.zip"
        asset = assets[name]
        url = f"{base}/{name}"
        if asset["browser_download_url"] != url or asset.get("size", 0) <= 0:
            raise ValueError(f"Invalid release asset: {name}")
        digest = asset.get("digest") or ""
        checksum = digest.removeprefix("sha256:")
        if assets_dir is not None:
            with (assets_dir / name).open("rb") as archive:
                checksum = hashlib.file_digest(archive, "sha256").hexdigest()
            if digest and digest != f"sha256:{checksum}":
                raise ValueError(f"Release digest mismatch: {name}")
        elif not digest.startswith("sha256:"):
            raise ValueError(f"Missing SHA256 digest: {name}; provide --assets-dir")
        if not re.fullmatch(r"[0-9a-f]{64}", checksum):
            raise ValueError(f"Invalid SHA256 digest: {name}")
        return {"url": url, "hash": checksum}

    arm = package("aarch64-apple-darwin")
    intel = package("x86_64-apple-darwin")
    scoop = {
        "version": version,
        "description": "Keyboard-driven mouse control and window management",
        "homepage": REPOSITORY,
        "license": "GPL-3.0-or-later",
        "architecture": {
            "64bit": package("x86_64-pc-windows-msvc"),
            "arm64": package("aarch64-pc-windows-msvc"),
        },
        "extract_dir": "KeySteer",
        "bin": [["KeySteer.exe", "keysteer"]],
        "shortcuts": [["KeySteer.exe", "KeySteer"]],
        "pre_install": RESTORE,
        "pre_uninstall": BACKUP,
        "notes": [
            "Exit KeySteer before updating. Use scoop update keysteer for package-managed upgrades.",
            "User configurations and workspace.ksw are backed up on update/uninstall and restored on install.",
        ],
    }
    cask = f'''# Generated by packaging/package-managers/generate.py; do not edit version or hashes.
cask "keysteer" do
  arch arm: "aarch64", intel: "x86_64"

  version "{version}"
  sha256 arm:   "{arm['hash']}",
         intel: "{intel['hash']}"

  url "{base}/KeySteer-v#{{version}}-#{{arch}}-apple-darwin.zip"
  name "KeySteer"
  desc "Keyboard-driven mouse control and window management"
  homepage "{REPOSITORY}"

  depends_on macos: ">= :sonoma"

  app "KeySteer/KeySteer.app"

  caveats <<~EOS
    Grant KeySteer Accessibility and Screen Recording permissions in System Settings.
    Exit KeySteer before running brew upgrade --cask keysteer.
    User data is stored in ~/Library/Application Support/KeySteer/.
  EOS
end
'''
    # Resolve and validate all four assets before touching either manifest.
    root = Path(root)
    for relative, content in {
        "Casks/keysteer.rb": cask,
        "bucket/keysteer.json": json.dumps(scoop, indent=4) + "\n",
    }.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return version


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release_json", type=Path)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--assets-dir", type=Path)
    args = parser.parse_args()
    print(generate(json.loads(args.release_json.read_text(encoding="utf-8")), args.root, args.assets_dir))
